// Generates the Week 5 n8n Code-node sources from ONE source of truth (web/src/lib/visibility/core.ts).
//   node scripts/build-week5-nodes.mjs          → writes ../n8n/week5/*.node.js
//   import { buildWeek5Nodes } (tests)          → returns { file: code } without writing
// Bodies marked `// @core` get the type-stripped core prepended (n8n Code nodes cannot import modules).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const CORE = here("../src/lib/visibility/core.ts");
const BODIES = here("../../n8n/week5/bodies/");
const OUT = here("../../n8n/week5/");

export function coreJs() {
  const ts = readFileSync(CORE, "utf8").replace(/\r\n/g, "\n");
  return stripTypeScriptTypes(ts, { mode: "strip" })
    .replace(/^export (?=(const|function|let)\b)/gm, "")
    .split("\n")
    .map((l) => l.replace(/\s+$/, ""))
    .filter((l) => l.trim() && !/^\s*\/\//.test(l))
    .join("\n");
}

/** Top-level declarations of the stripped core, in source order: { name, code }. */
export function coreDecls(js = coreJs()) {
  const decls = [];
  for (const line of js.split("\n")) {
    const m = line.match(/^(?:const|let|function)\s+([A-Za-z_$][\w$]*)/);
    if (m) decls.push({ name: m[1], lines: [line] });
    else if (decls.length) decls[decls.length - 1].lines.push(line);
  }
  return decls.map((d) => ({ name: d.name, code: d.lines.join("\n") }));
}

/** Only the declarations a body uses (transitively) — keeps each n8n Code node small. */
export function coreFor(body, decls = coreDecls()) {
  const uses = (text, name) => new RegExp(`(^|[^\\w$.])${name.replace(/\$/g, "\\$")}(?![\\w$])`).test(text);
  const need = new Set(decls.filter((d) => uses(body, d.name)).map((d) => d.name));
  let grew = true;
  while (grew) {
    grew = false;
    for (const d of decls) if (need.has(d.name)) for (const e of decls) if (!need.has(e.name) && uses(d.code, e.name)) (need.add(e.name), (grew = true));
  }
  return decls.filter((d) => need.has(d.name)).map((d) => d.code).join("\n");
}

export function buildWeek5Nodes() {
  const decls = coreDecls();
  const out = {};
  for (const f of readdirSync(BODIES).filter((x) => x.endsWith(".js")).sort()) {
    const body = readFileSync(BODIES + f, "utf8").replace(/\r\n/g, "\n").trim();
    const needsCore = body.startsWith("// @core");
    const header = `// GENERATED by web/scripts/build-week5-nodes.mjs from n8n/week5/bodies/${f}${needsCore ? " + web/src/lib/visibility/core.ts" : ""}. Do not edit.\n`;
    const own = body.replace(/^\/\/ @core\n/, "");
    out[f.replace(/\.js$/, ".node.js")] = header + (needsCore ? `${coreFor(own, decls)}\n// ---------------- node body ----------------\n${own}\n` : body + "\n");
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = buildWeek5Nodes();
  for (const [name, code] of Object.entries(files)) writeFileSync(OUT + name, code);
  console.log(Object.entries(files).map(([n, c]) => `${n} ${c.length}`).join("\n"));
}
